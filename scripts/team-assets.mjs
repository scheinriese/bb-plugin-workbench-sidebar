// Trusted, repository-owned SVGs only; never use RPC strings as markup.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const root = new URL("../assets/team/", import.meta.url);
const entries = ["h2", "h3"].flatMap((system) =>
  readdirSync(new URL(`${system}/`, root))
    .filter((name) => name.endsWith(".svg"))
    .sort()
    .map((name) => {
      const key = `${system}/${name.replace(/\.svg$/, "")}`;
      return `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(new URL(`${system}/${name}`, root), "utf8").trim())},`;
    }),
);
writeFileSync(
  new URL("avatar-data.ts", root),
  `// Generated by scripts/team-assets.mjs from the adjacent SVG sources.\nexport const teamAvatarImages: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
